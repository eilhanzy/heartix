#include "string.h"
#include "stdlib.h"

char* strndup(const char* s, size_t n) {
	if(!s) {
		return 0;
	}

	size_t len = 0;
	while(len < n && s[len] != '\0') {
		++len;
	}

	char* out = (char*)malloc(len + 1);
	if(!out) {
		return 0;
	}

	memcpy(out, s, len);
	out[len] = '\0';
	return out;
}
